// node scripts/lab-routes.mjs    Writes one dev-only lab page per cutscene (app/lab/cut/<name>/page.jsx) and per hero look
// (app/lab/hero/<id>/page.jsx). Each page imports its own cutscene only, so a cutscene that fails to compile breaks its own
// page and no other. Names starting with "_" become "x-<name>" (Next does not route underscore folders). Safe to re-run.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const CUTS = path.join(root, "lib/anime/cutscenes"), LOOKS = path.join(root, "lib/anime/kit/hero/looks");
export const routeOf = (dock) => (dock.startsWith("_") ? `x-${dock.slice(1)}` : dock);

const guard = `if (process.env.NEXT_PUBLIC_VERCEL_ENV === "production") return null;`;
const cutPage = (dock) => `"use client";
// generated by scripts/lab-routes.mjs: the lab page of one cutscene, isolated from every other
import CutCore from "../../../../components/anime/CutCore.jsx";

const load = async () => {
  const out = { id: "${dock}", scene: null, build: null, error: null };
  try { out.scene = (await import("../../../../lib/anime/cutscenes/${dock}/scene.js")).default; } catch (e) { out.error = { file: "${dock}/scene.js", message: String(e?.stack ?? e) }; console.error(e); }
  try { out.build = (await import("../../../../lib/anime/cutscenes/${dock}/build.js")).default; } catch (e) { out.error ??= { file: "${dock}/build.js", message: String(e?.stack ?? e) }; console.error(e); }
  return out;
};

export default function Page() {
  ${guard}
  return <CutCore id="${dock}" load={load} />;
}
`;
const heroPage = (id) => `"use client";
// generated by scripts/lab-routes.mjs: the hero test scene with one look, isolated from every other look
import CutCore from "../../../../components/anime/CutCore.jsx";

const load = async () => {
  const out = { id: "_hero", scene: null, build: null, error: null };
  globalThis.__heroLookId = "${id}";
  globalThis.__heroLoadLook = (id) => (id === "${id}" ? import("../../../../lib/anime/kit/hero/looks/${id}.js") : Promise.reject(new Error("this page holds the look ${id} only")));
  try { out.scene = (await import("../../../../lib/anime/cutscenes/_hero/scene.js")).default; } catch (e) { out.error = { file: "_hero/scene.js", message: String(e?.stack ?? e) }; console.error(e); }
  try { out.build = (await import("../../../../lib/anime/cutscenes/_hero/build.js")).default; } catch (e) { out.error ??= { file: "_hero/build.js", message: String(e?.stack ?? e) }; console.error(e); }
  return out;
};

export default function Page() {
  ${guard}
  return <CutCore id="_hero" load={load} />;
}
`;

function write(file, text) {
  if (fs.existsSync(file) && fs.readFileSync(file, "utf8") === text) return 0;
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, text);
  return 1;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  let n = 0, cuts = 0, looks = 0;
  for (const d of fs.readdirSync(CUTS, { withFileTypes: true })) {
    if (!d.isDirectory() || d.name === "_template" || d.name === "_hero" || d.name === "framework") continue;
    if (!fs.existsSync(path.join(CUTS, d.name, "scene.js")) || !fs.existsSync(path.join(CUTS, d.name, "build.js"))) continue;
    n += write(path.join(root, "app/lab/cut", routeOf(d.name), "page.jsx"), cutPage(d.name)); cuts++;
  }
  for (const f of fs.readdirSync(LOOKS)) {
    if (!f.endsWith(".js") || f.includes(".parts.") || f.startsWith("_")) continue;
    const id = f.slice(0, -3);
    if (!/^[\w-]+$/.test(id)) continue;
    n += write(path.join(root, "app/lab/hero", id, "page.jsx"), heroPage(id)); looks++;
  }
  console.log(`lab-routes: ${cuts} cutscene pages, ${looks} hero look pages, ${n} written`);
}
